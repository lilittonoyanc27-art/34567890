import { Difficulty, QuestionItem } from './types';

// Helper for Game 1: Armenian -> Spanish
function mkG1(level: Difficulty, rows: [string, string, string?][]): QuestionItem[] {
  return rows.map(([hy, es, note], idx) => ({
    id: `g1_${level}_${idx + 1}`,
    gameId: 'traduccion_supersonica',
    level,
    prompt: hy,
    answer: `${es} — ${hy}`,
    answerDetail: note,
  }));
}

// Helper for Game 2: Spanish -> Armenian
function mkG2(level: Difficulty, rows: [string, string, string?][]): QuestionItem[] {
  return rows.map(([es, hy, note], idx) => ({
    id: `g2_${level}_${idx + 1}`,
    gameId: 'traduccion_reves',
    level,
    prompt: es,
    answer: hy,
    answerDetail: note ? `${es} — ${hy} (${note})` : `${es} — ${hy}`,
  }));
}

// Helper for Game 3: Construye la frase
function mkG3(level: Difficulty, rows: [string[], string, string][]): QuestionItem[] {
  return rows.map(([words, answer, hy], idx) => ({
    id: `g3_${level}_${idx + 1}`,
    gameId: 'construye_frase',
    level,
    prompt: words.join(' / '),
    promptHy: hy,
    words,
    answer,
  }));
}

// Helper for Game 4: La palabra misteriosa
function mkG4(level: Difficulty, rows: [string, string, string, string?][]): QuestionItem[] {
  return rows.map(([descEs, descHy, answer, hyWord], idx) => ({
    id: `g4_${level}_${idx + 1}`,
    gameId: 'palabra_misteriosa',
    level,
    prompt: descEs,
    promptHy: descHy,
    answer,
    answerDetail: hyWord ? `Հայերեն՝ ${hyWord}` : undefined,
  }));
}

